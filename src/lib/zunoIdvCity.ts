export function deriveIdvCity(vehicleRegNo: string): string {
  const no = (vehicleRegNo || "").toUpperCase().replace(/[^A-Z0-9]/g, "");
  const code = no.match(/^([A-Z]{2}[0-9]{1,2})/)?.[1];
  if (code && RTO_TO_IDV_CITY[code]) return RTO_TO_IDV_CITY[code];
  const prefix = no.match(/^[A-Z]{2}/)?.[0];
  if (prefix && STATE_PREFIX_TO_IDV_CITY[prefix]) return STATE_PREFIX_TO_IDV_CITY[prefix];
  return "AHMEDABAD";
}
